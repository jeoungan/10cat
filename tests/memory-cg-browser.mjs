import assert from 'node:assert/strict';
import {mkdir,writeFile} from 'node:fs/promises';
import {pathToFileURL} from 'node:url';
import path from 'node:path';
import {createGame,SAVE_KEY} from '../game.js';
const {chromium}=await import(pathToFileURL(path.join(process.env.USERPROFILE,'.cache/codex-runtimes/codex-primary-runtime/dependencies/node/node_modules/playwright/index.mjs')));
let seed;
const fixture=createGame({getItem:()=>null,setItem:(_,value)=>seed=value});
for(const id of ['bori','mochi','nabi'])fixture.state.cats[id].affection=30;
fixture.equipOutfit('mochi','ribbon');fixture.selectCat('mochi');
const browser=await chromium.launch({channel:'chrome',headless:true});
const page=await browser.newPage({viewport:{width:1440,height:1050}});
await page.addInitScript(({key,seed})=>{if(!localStorage.getItem(key))localStorage.setItem(key,seed);},{key:SAVE_KEY,seed});
const errors=[];page.on('pageerror',error=>errors.push(error.message));
const state=()=>page.evaluate(()=>JSON.parse(window.render_game_to_text()));
const album=()=>page.getByRole('button',{name:'추억 앨범',exact:true}).click();
const ending=async(id,choice=0)=>{
 await page.locator(`[data-story="${id}"]`).click();
 await page.locator('[data-command="dialogue-next"]').click();
 await page.locator('[data-command="dialogue-next"]').click();
 await page.locator(`[data-choice="${choice}"]`).click();
 await page.locator('.cutscene-background').evaluate(image=>image.decode());
};
await mkdir('output/review-1143',{recursive:true});
try{
 await page.goto('http://127.0.0.1:4173/',{waitUntil:'networkidle'});
 const before=await state();
 await album();assert.equal(await page.locator('[data-story="mochi"] .memory-cg').count(),0,'Uncollected album does not reveal the ending artwork');
 await page.locator('[data-story="mochi"]').click();
 assert.equal(await page.locator('.cutscene-cat[data-outfit-art="ribbon"]').count(),1,'Earlier story pages retain the chosen outfit');
 await page.keyboard.press('Escape');
 await ending('mochi');
 assert.match(await page.locator('.cutscene-background').getAttribute('src'),/mochi-memory\.png$/);
 assert.match(await page.locator('.cutscene-background').getAttribute('alt'),/모찌/);
 assert.equal(await page.locator('.cutscene-cat').count(),0,'Memory art does not render a second cat on top');
 const firstText=await page.locator('.dialogue-text').innerText();
 await page.locator('#modal').screenshot({path:'output/review-1143/mochi-memory-desktop.png'});
 await page.reload({waitUntil:'networkidle'});
 assert.equal(await page.locator('.dialogue-text').innerText(),firstText);
 assert.match(await page.locator('.cutscene-background').getAttribute('src'),/mochi-memory\.png$/);
 assert.equal((await state()).cat.outfit,'ribbon');
 await page.locator('[data-command="dialogue-next"]').click();
 const completed=await state();assert.equal(completed.coins,before.coins+20);assert.equal(completed.cat.affection,before.cat.affection+5);
 assert.equal(completed.album.filter(entry=>entry.catId==='mochi').length,1);
 await album();assert.match(await page.locator('[data-story="mochi"] .memory-cg').getAttribute('src'),/mochi-memory\.png$/);
 await page.locator('[data-story="mochi"] .memory-cg').evaluate(image=>image.decode());
 await page.locator('[data-story="mochi"]').screenshot({path:'output/review-1143/mochi-album.png'});
 await page.setViewportSize({width:390,height:844});await ending('mochi',1);
 assert.notEqual(await page.locator('.dialogue-text').innerText(),firstText,'Both story branches still have their own response');
 const box=await page.locator('.dialogue-box').boundingBox(),modal=await page.locator('#modal').boundingBox();
 assert(box.y>=modal.y&&box.y+box.height<=modal.y+modal.height&&box.y+box.height<=844);
 assert(await page.locator('#modal').evaluate(el=>el.scrollWidth<=el.clientWidth));
 await page.locator('#modal').screenshot({path:'output/review-1143/mochi-memory-mobile.png'});
 await page.keyboard.press('Escape');
 assert.equal((await state()).coins,completed.coins);assert.equal((await state()).cat.outfit,'ribbon');
 await page.getByRole('button',{name:'우리 집',exact:true}).click();
 assert.equal(await page.locator('.scene-cat.selected [data-outfit-art="ribbon"]').count(),1,'The equipped portrait returns after the memory closes');
 await album();await ending('bori');assert.match(await page.locator('.cutscene-background').getAttribute('src'),/bori-memory\.png$/);await page.keyboard.press('Escape');
 await ending('nabi');assert.equal(await page.locator('.cutscene-cat').count(),1,'A cat without dedicated CG keeps its existing portrait scene');await page.keyboard.press('Escape');
 assert.equal(await page.locator('[data-command="motion-toggle"], [data-command="motion-replay"], [data-motion-frame]').count(),0);
 assert.deepEqual(errors,[]);
 await writeFile('output/review-1143/memory-result.json',JSON.stringify({ok:true,errors,coverage:['mochi-dedicated-ending','own-alt','no-duplicate-cat','outfit-before-after','ending-reload','one-time-reward','collected-album-art','uncollected-no-spoiler','two-branches','mobile-fit','bori-CG-retained','other-cat-fallback']},null,2));
 console.log('PASS: Mochi memory CG, saved ending, dressed return, album reveal, both branches, mobile, existing Bori and other-cat fallback; no page errors.');
}finally{await browser.close();}
