import assert from 'node:assert/strict';
import { mkdir,writeFile } from 'node:fs/promises';
import { pathToFileURL } from 'node:url';
import path from 'node:path';
let pw;
try { pw=await import('playwright'); } catch { pw=await import(pathToFileURL(path.join(process.env.USERPROFILE,'.cache/codex-runtimes/codex-primary-runtime/dependencies/node/node_modules/playwright/index.mjs'))); }
const browser=await pw.chromium.launch({channel:'chrome',headless:true});
const page=await browser.newPage({viewport:{width:1440,height:1050}});
const errors=[];
page.on('pageerror',error=>errors.push(error.message));
const state=()=>page.evaluate(()=>JSON.parse(window.render_game_to_text()));
const choose=async index=>{
 await page.locator('.story-button').click();
 await page.locator('[data-command="dialogue-next"]').click();
 await page.locator('[data-command="dialogue-next"]').click();
 await page.locator(`[data-choice="${index}"]`).click();
 assert.match(await page.locator('.dialogue-page').innerText(),/04\s*\/\s*04/);
 return page.locator('.dialogue-text').innerText();
};
await mkdir('output/story-qa',{recursive:true});
try {
 await page.goto('http://127.0.0.1:4173/',{waitUntil:'networkidle'});
 await page.locator('.care-actions [data-action="pet"]').click();
 await page.waitForFunction(()=>JSON.parse(window.render_game_to_text()).motion?.ready);
 const firstCaption=await page.locator('.motion-frame-caption').innerText();
 await page.evaluate(()=>window.advanceTime(6500));
 assert.equal(await page.locator('.motion-frame-caption').innerText(),firstCaption,'Caption remains readable across loops');
 assert.equal((await state()).motion.playing,true);
 assert.equal(await page.locator('[data-command="motion-toggle"], [data-motion-frame]').count(),0);
 await page.keyboard.press('Escape');
 const before=await state();
 const branch0=await choose(0);
 await page.reload({waitUntil:'networkidle'});
 assert.equal(await page.locator('.dialogue-text').innerText(),branch0,'Selected branch survives refresh');
 assert.match(await page.locator('.cutscene-background').getAttribute('src'),/bori-memory/);
 await page.screenshot({path:'output/story-qa/choice-desktop.png',fullPage:true});
 await page.locator('[data-command="dialogue-next"]').click();
 const completed=await state();
 assert.equal(completed.album.length,1);
 assert.equal(completed.coins,before.coins+20);
 assert.equal(completed.cat.affection,before.cat.affection+5);
 const branch1=await choose(1);
 assert.notEqual(branch1,branch0,'Each choice receives its own visible response');
 await page.setViewportSize({width:390,height:844});
 await page.reload({waitUntil:'networkidle'});
 assert.equal(await page.locator('.dialogue-text').innerText(),branch1,'Replay branch also survives refresh');
 assert(await page.locator('#modal').evaluate(el=>el.scrollWidth<=el.clientWidth),'Mobile story does not overflow horizontally');
 const box=await page.locator('.dialogue-box').boundingBox();
 assert(box.y>=0&&box.y+box.height<=844,'The response and completion control fit in the mobile viewport');
 await page.screenshot({path:'output/story-qa/choice-mobile.png',fullPage:true});
 await page.locator('[data-command="dialogue-next"]').click();
 assert.equal((await state()).coins,completed.coins,'Replaying another choice gives no extra coins');
 assert.equal((await state()).cat.affection,completed.cat.affection,'Replaying another choice gives no extra affection');
 assert.equal((await state()).album.length,1);
 await choose(0);await page.keyboard.press('Escape');
 assert.equal((await state()).coins,completed.coins);
 assert.equal((await state()).cat.affection,completed.cat.affection);
 assert.deepEqual(errors,[]);
 await writeFile('output/story-qa/result.json',JSON.stringify({ok:true,branch0,branch1,errors,coverage:['distinct-choice-responses','choice-persistence','replay-persistence','single-completion-reward','cancel','four-pages','memory-CG','desktop-mobile','stable-motion-caption','no-player-controls']},null,2));
 console.log('PASS: distinct story choices, refresh and replay persistence, single reward, cancel, four-page CG, mobile fit, stable motion caption, zero page errors.');
} finally { await browser.close(); }
